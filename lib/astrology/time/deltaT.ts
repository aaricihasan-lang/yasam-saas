const msOfYear = (y: number) => Date.UTC(y, 0, 1);

/** ΔT (s) verilen UT1 anı için (ms ekseni = UT1); tablo aralığı dışı → null. Uçlarda 1 yıllık tampon (kök tarama için) sabit değer. */
export function deltaTModelSeconds(ut1Ms: number): number | null {
  if (!Number.isFinite(ut1Ms)) return null;
  const y = new Date(ut1Ms).getUTCFullYear();
  if (y === DELTA_T_FIRST_YEAR - 1) return T[0];
  if (y === DELTA_T_LAST_YEAR + 1) return T[T.length - 1];
  if (y < DELTA_T_FIRST_YEAR || y > DELTA_T_LAST_YEAR) return null;
  const i = y - DELTA_T_FIRST_YEAR;
  if (i === T.length - 1) return T[i];
  const f = (ut1Ms - msOfYear(y)) / (msOfYear(y + 1) - msOfYear(y));
  return T[i] + (T[i + 1] - T[i]) * f;
}

export type DeltaTClass = "observed" | "historical_model" | "predicted";
/** 1800 öncesi: tarihsel model (teleskop öncesi/erken gözlem); 1800–2025: gözlem dönemi; sonrası: öngörü. */
export function deltaTClassOf(ut1Ms: number): DeltaTClass {
  const y = new Date(ut1Ms).getUTCFullYear();
  if (y > DELTA_T_LAST_OBSERVED_YEAR) return "predicted";
  if (y < 1800) return "historical_model";
  return "observed";
}
